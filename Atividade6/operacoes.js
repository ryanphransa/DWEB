let nota1 = parseFloat(prompt("Digite o primeiro nmr: "))
let nota2 = parseFloat(prompt("Digite o segundo nmr: "))

let sum = nota1 + nota2
let sub = nota1 - nota2
let product = nota1 * nota2
let division = nota1 / nota2
let rest = nota1 % nota2

alert("Soma dos dois nmrs: " + sum.toFixed(2))
alert("Subtracao dos dois nmrs: " + sub.toFixed(2))
alert("Produto dos dois nmrs: " + product.toFixed(2))
alert("Divisao dos dois nmrs: " + division.toFixed(2))
alert("Resto dos dois nmrs: " + rest.toFixed(2))

